"""Shared response contracts for community energy flow reports.

These models define the common API payload used by status,
simulation, and flexibility endpoints.
"""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, Field


class TimeSeries(BaseModel):
    """Timestamped values with a declared physical or monetary unit.

    Each point is ``(unix_timestamp_ms, value)``.  Timestamps use UTC Unix
    milliseconds so the same series can be consumed consistently by charting
    clients.
    """
    points: list[tuple[int, float]] = Field(default_factory=list)
    unit: str = Field(..., min_length=1, examples=["W"])


class ReportWindow(BaseModel):
    """Time window covered by a report."""
    start_datetime: datetime
    end_datetime: datetime
    timestep_minutes: int = Field(default=15, gt=0)


class EnergySummary(BaseModel):
    """Community-level energy, cost, and emissions KPIs."""
    imported_energy_wh: float
    exported_energy_wh: float
    produced_energy_wh: float
    consumed_energy_wh: float
    self_consumed_energy_wh: float
    self_consumption_pct: float
    self_sufficiency_pct: float
    expenses_eur: float
    co2_emissions_kg: float


class EnergySeries(BaseModel):
    """Common community power, energy, and price profiles."""
    energy_price: TimeSeries
    consumption_power: TimeSeries
    production_power: TimeSeries
    grid_import_power: TimeSeries
    grid_export_power: TimeSeries
    battery_charge_power: TimeSeries
    battery_discharge_power: TimeSeries
    stored_energy: TimeSeries


class ServicePointReport(BaseModel):
    """Optional per-service-point summary included in a community report."""
    service_point_id: str
    code: str
    role: Literal["producer", "consumer", "prosumer"] | None = None
    summary: EnergySummary


class EnergyCommunityReport(BaseModel):
    """Fields common to every community energy-flow report."""
    window: ReportWindow
    summary: EnergySummary
    series: EnergySeries
    community_type: str | None = None
    service_points: list[ServicePointReport] | None = None


class StatusReport(EnergyCommunityReport):
    """Report generated from the current/reported community status."""
    kind: Literal["status"] = "status"


class SimulationReport(EnergyCommunityReport):
    """Report generated by a simulation enpoint."""
    kind: Literal["simulation"] = "simulation"


class FlexibilityReport(EnergyCommunityReport):
    """Report generated by flexibility offer and activation optimisation."""
    kind: Literal["flexibility"] = "flexibility"


class SimulationDetails(BaseModel):
    """Simulation-specific inputs that explain the generated report."""
    strategy: str
    battery_discharge_scope: Literal["local", "community"]


class FlexibilityMarketOfferChunk(BaseModel):
    """A contiguous 15-minute-or-greater flexibility-market offer."""
    direction: Literal["up", "down"]
    start_datetime: datetime
    end_datetime: datetime
    power_w: float = Field(gt=0)
    price: float
    price_uom: str = Field(..., min_length=1)


class ServicePointFlexibilityOffer(BaseModel):
    """Flexibility offers allocated to one service point."""
    service_point_id: str
    code: str
    offer_up_power: TimeSeries
    offer_down_power: TimeSeries
    market_offer_chunks: list[FlexibilityMarketOfferChunk] = Field(default_factory=list)


class FlexibilityDetails(BaseModel):
    """Flexibility-specific schedules and optimisation metadata."""
    request_id: str
    solver_status: str
    baseline_power: TimeSeries
    activated_power: TimeSeries
    offer_up_power: TimeSeries
    offer_down_power: TimeSeries
    market_offer_chunks: list[FlexibilityMarketOfferChunk] = Field(default_factory=list)
    service_point_offers: list[ServicePointFlexibilityOffer] = Field(default_factory=list)
    objective_eur: float


class StatusResponse(BaseModel):
    """Response envelope for the future status report endpoint."""
    report: StatusReport


class SimulationResponse(BaseModel):
    """Response envelope for the future simulation report endpoint."""
    report: SimulationReport
    simulation: SimulationDetails


class FlexibilityResponse(BaseModel):
    """Response envelope for the future flexibility report endpoint."""
    report: FlexibilityReport
    flexibility: FlexibilityDetails
